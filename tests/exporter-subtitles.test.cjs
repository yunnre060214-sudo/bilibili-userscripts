const code = fs.readFileSync(path.join(__dirname, '..', 'bilibili-comment-thread-exporter.user.js'), 'utf8');

function load(extra = {}) {
  const location = { href: 'https://www.bilibili.com/video/BV1234567890?p=2', pathname: '/video/BV1234567890' };
  const context = vm.createContext({
    URL, AbortController, setTimeout, clearTimeout, console,
    location,
    document: { title: '原视频', querySelector: () => null },
    window: {},
    ...extra,
  });
  vm.runInContext(code.replace('  boot();', `
    globalThis.api = {
      captureVideoSource, fetchVideoSubtitles, fetchThread, formatThreadMarkdown,
      normalizeSubtitleUrl, normalizeSubtitleCues,
      beginExportTask, cancelActiveTask, requestJsonWithRetry,
      setRequest(fn) { dependencies.requestJson = fn; },
      setDelay(fn) { dependencies.waitBetweenPages = fn; },
    };
  `), context);
  return { api: context.api, location };
}

function source(api) {
  return api.captureVideoSource({ oid: '123', type: 1 });
}

const view = (overrides = {}) => ({ code: 0, data: {
  aid: 123, bvid: 'BV1234567890', cid: 100,
  pages: [{ page: 1, cid: 100, part: '第一集' }, { page: 2, cid: 200, part: '第二集' }],
  ...overrides,
} });
const track = (lan = 'zh-CN', url = '//i0.hdslb.com/bfs/subtitle/manual.json', extra = {}) => ({
  lan, lan_doc: lan === 'zh-CN' ? '中文' : lan, subtitle_url: url, ...extra,
});
const player = tracks => ({ code: 0, data: { subtitle: { subtitles: tracks } } });
const body = (...texts) => ({ body: texts.map((content, index) => ({ from: index * 2, to: index * 2 + 1, content })) });

function fixtures(api, { tracks = [track()], video = view(), subtitle = body('字幕第一句', '字幕第二句'), respond } = {}) {
  const requests = [];
  api.setRequest(async (rawUrl, task, options) => {
    const url = new URL(rawUrl);
    requests.push({ url, task, options });
    if (respond) {
      const response = await respond(url, task, options);
      if (response !== undefined) return response;
    }
    if (url.pathname === '/x/web-interface/view') return video;
    if (url.hostname === 'api.bilibili.com') return player(tracks);
    return subtitle;
  });
  return requests;
}

function markdown(api, subtitles, videoSource = source(api)) {
  return api.formatThreadMarkdown({
    source: { ...videoSource, rootRpid: '1', selectedRpid: '1' },
    exporter: { complete: true, actualReplyCount: 1, expectedReplyCount: 1 },
    root: { rpid: '1', user: { name: '根作者' }, message: '根评论正文', time: {} },
    replies: [{ rpid: '2', parent: '1', root: '1', user: { name: '回复作者' }, message: '回复正文', time: {} }],
    subtitles,
  });
}

test('subtitles use current P2 CID and prefer human Chinese over AI Chinese or English', async () => {
  const { api } = load();
  const requests = fixtures(api, { tracks: [
    track('en', '//i0.hdslb.com/english.json'),
    track('ai-zh', '//aisubtitle.hdslb.com/ai.json', { ai_type: 1 }),
    track('zh-CN', ''),
    track(),
  ] });
  const videoSource = source(api);
  const subtitles = await api.fetchVideoSubtitles(videoSource);
  assert.equal(subtitles.status, 'ok');
  assert.equal(subtitles.language, 'zh-CN');
  assert.equal(subtitles.autoGenerated, false);
  assert.equal(videoSource.cid, '200');
  assert.equal(videoSource.part, '第二集');
  assert.equal(requests[0].url.searchParams.get('aid'), '123');
  assert.equal(requests[1].url.searchParams.get('cid'), '200');
  assert.equal(requests[2].url.href, 'https://i0.hdslb.com/bfs/subtitle/manual.json');
  assert.equal(requests[0].options.anonymous, false);
  assert.equal(requests[2].options.anonymous, true);
  assert.ok(requests.every(item => item.options.timeoutMs === 8000 && item.options.retries === 1));
});

test('subtitle Markdown precedes the comment floor and preserves repeats and escapes formatting', async () => {
  const { api } = load();
  fixtures(api, { subtitle: body('相同台词', '相同台词', '# 标题\n<script>x</script> & **文字**') });
  const subtitles = await api.fetchVideoSubtitles(source(api));
  const result = markdown(api, subtitles);
  assert.ok(result.indexOf('## 视频字幕正文') < result.indexOf('## 根评论'));
  assert.ok(result.indexOf('相同台词') < result.indexOf('## 阅读说明'));
  assert.equal(result.split('相同台词').length - 1, 2);
  assert.match(result, /\\# 标题/);
  assert.match(result, /&lt;script&gt;x&lt;\/script&gt; &amp; \\\*\\\*文字\\\*\\\*/);
  assert.doesNotMatch(result, /<script>|subtitle\/manual\.json/);
  assert.match(result, /根评论正文/);
  assert.match(result, /回复正文/);
  assert.match(result, /回复 \[0001\]\(#msg-0001\)/);
});

